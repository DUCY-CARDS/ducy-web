// Builds the Hold'em hand ranking and writes src/holdem-rank.js.
//
//   node scripts/rank-holdem.mjs --bin <holdem_hand_quality> [--data <dir>] [--iters 3]
//       [--range 0.25] [--w-hu 0.35] [--w-fav 0.4] [--w-implied 0.25] [--continue 0.7] [--favorable 0.5] [--flops 600]
//
// Same method as the Omaha ranking (fit-omaha-rank.mjs), but Hold'em has only
// 169 starting-hand classes, so every class is measured directly with ducy's
// `holdem_hand_quality` example and no model is needed:
//   round 0: rank classes by raw equity against a random hand
//   each round: opponents play the top 25% of combos from the previous ranking;
//     score = weighted raw equity + favorable-flop rate + net implied odds
//     (z-scored over all 1,326 combos). A flop is favorable when the hand has
//     at least 50% equity against range hands that give action there (at least
//     70% equity against a random hand on that flop); implied odds reward
//     making trips or better and winning against them, and penalize making a
//     big hand that still loses (set under set, the low end of a straight)
// A class's percentile is the middle of its combos in the final order, so
// "top X%" means about X% of all combos.

import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { execFileSync } from 'child_process';

const args = Object.fromEntries(process.argv.slice(2).reduce((a, x, i, all) => (x.startsWith('--') ? [...a, [x.slice(2), all[i + 1]]] : a), []));
if (!args.bin) {
  console.error('usage: node scripts/rank-holdem.mjs --bin <holdem_hand_quality> [--data <dir>] [--iters 3] ...');
  process.exit(2);
}
const DIR = args.data || '.';
const ITERS = +(args.iters || 3);
const RANGE_TOP = +(args.range || 0.25);
// Score weights: raw equity, favorable-flop rate, net implied odds.
const W = {hu: +(args['w-hu'] ?? 0.35), favorable: +(args['w-fav'] ?? 0.4), implied: +(args['w-implied'] ?? 0.25)};
const CONTINUE = args.continue || '0.7';
const FAVORABLE = args.favorable || '0.5';
const FLOPS = args.flops || '600';
const OUT = args.out || new URL('../src/holdem-rank.js', import.meta.url).pathname;
mkdirSync(DIR, {recursive: true});

function run(out, extra = []) {
  execFileSync(args.bin, [out, ...extra], {stdio: ['ignore', 'ignore', 'inherit']});
  const [head, ...lines] = readFileSync(out, 'utf8').trim().split('\n');
  const cols = head.split(',');
  return lines.map(l => Object.fromEntries(l.split(',').map((v, i) => [cols[i], i ? +v : v])));
}

// Combo-weighted z-scores, so the scale reflects the distribution of dealt hands.
function zscores(rows, key) {
  const w = rows.reduce((a, r) => a + r.combos, 0);
  const m = rows.reduce((a, r) => a + r.combos * r[key], 0) / w;
  const sd = Math.sqrt(rows.reduce((a, r) => a + r.combos * (r[key] - m) ** 2, 0) / w) || 1;
  return rows.map(r => (r[key] - m) / sd);
}

function ranks(xs) {
  const idx = xs.map((_, i) => i).sort((a, b) => xs[a] - xs[b]);
  const r = new Array(xs.length);
  idx.forEach((i, k) => { r[i] = k; });
  return r;
}
function spearman(a, b) {
  const ra = ranks(a), rb = ranks(b), n = a.length;
  return 1 - 6 * ra.reduce((s, x, i) => s + (x - rb[i]) ** 2, 0) / (n * (n * n - 1));
}

function topRange(rows, scores) {
  const order = rows.map((r, i) => i).sort((a, b) => scores[b] - scores[a]);
  const picked = [];
  let combos = 0;
  for (const i of order) {
    if (combos >= RANGE_TOP * 1326) break;
    picked.push(rows[i].class);
    combos += rows[i].combos;
  }
  return picked;
}

const base = run(`${DIR}/round0.csv`);
let scores = base.map(r => r.hu);
let rows = base;
for (let it = 1; it <= ITERS; it++) {
  const range = topRange(rows, scores);
  writeFileSync(`${DIR}/range.txt`, range.join(', ') + '\n');
  rows = run(`${DIR}/round${it}.csv`, [`range=${DIR}/range.txt`, `seed=${it}`, `continue=${CONTINUE}`, `favorable=${FAVORABLE}`, `flops=${FLOPS}`]);
  for (const r of rows) r.implied = r.implied_win - r.implied_loss;
  const z = Object.fromEntries(Object.keys(W).map(k => [k, zscores(rows, k)]));
  const next = rows.map((_, i) => Object.keys(W).reduce((a, k) => a + W[k] * z[k][i], 0));
  console.log(`round ${it}: opponents play ${range.length} classes; ranking vs previous round, rank corr ${spearman(next, scores).toFixed(3)}`);
  scores = next;
}

const order = rows.map((r, i) => i).sort((a, b) => scores[b] - scores[a]);
const pct = {};
let cum = 0;
for (const i of order) {
  pct[rows[i].class] = +((cum + rows[i].combos / 2) / 1326 * 100).toFixed(2);
  cum += rows[i].combos;
}
const header = `// Generated by scripts/rank-holdem.mjs. Do not edit by hand.
// Hold'em hand classes ranked by ${W.hu} x raw equity vs a random hand + ${W.favorable} x favorable-flop rate
// (>= ${FAVORABLE} equity against top-${RANGE_TOP * 100}% opponents who give action on the flop, i.e. >= ${CONTINUE}
// equity vs a random hand there) + ${W.implied} x net implied odds (how often the hand makes trips or better
// and wins against those opponents, minus how often it makes one and loses), all z-scored over combos;
// ${ITERS} rounds of refining the opponent range.
// HOLDEM_PERCENTILE[class] is the middle of the class's combos in that order
// (0 = best, 100 = worst), so "top X%" covers about X% of all 1,326 combos.
`;
writeFileSync(OUT, header +
  `export const HOLDEM_ORDER = ${JSON.stringify(order.map(i => rows[i].class))};\n` +
  `export const HOLDEM_PERCENTILE = ${JSON.stringify(pct)};\n`);
console.log(`wrote ${OUT}`);
console.log('top 20:', order.slice(0, 20).map(i => rows[i].class).join(' '));
for (const c of ['AA', 'AKs', 'AKo', 'KQs', 'JTs', 'T9s', '76s', '22', 'A5s', 'K9o', 'Q8o', '72o']) console.log(`  ${c.padEnd(4)} top ${pct[c].toFixed(1)}%`);
